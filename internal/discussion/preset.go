package discussion

// presets 是开场那几个**预设追问**：界面上排成几个按钮，点一下就把这句话问出去。
//
// 它们是 Go 侧的数据而不是 Svelte 里的文案，理由三条：
//
//   - 它不是装饰，是**讨论的第一条记录**。按下哪个按钮，讨论里就留下哪句话 ——
//     措辞该待的地方，是写下这条记录的那一侧。
//   - 界面上按的与记录里留的因此是同一份字，不会各说各话。
//   - 「至少三个、且含票据点名的那三个」是验收条款。前端不做自动化测试（spec），
//     摆在 Go 侧才有一条测试钉得住它。
//
// 措辞暂定：真正问出去的就是它，改词只改这一处（不必跟着动界面）。
// 不留配置里的覆盖口子：与打标签的提示词不同，这里改的是用户自己要说的话，
// 不是提示词，没有「换个说法试一版」的需求。
var presets = []string{
	"这步为什么",
	"还有别的解法吗",
	"我错在哪",
}

// Presets 返回预设追问的文案，顺序即界面上的顺序。
//
// 返回副本而不是那个切片本身：调用方改不动服务里的这一份。
func (s *Service) Presets() []string {
	out := make([]string, len(presets))
	copy(out, presets)
	return out
}
